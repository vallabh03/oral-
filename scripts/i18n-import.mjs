// Writes a reviewed/drafted translation (JSON object: English → translation) into the
// dictionary module the website uses.  Usage: node scripts/i18n-import.mjs te path/to/te.json
import fs from "node:fs";

const [lang, file] = process.argv.slice(2);
if (!/^[a-z]{2,3}$/.test(lang ?? "") || !file) {
  console.error("Usage: node scripts/i18n-import.mjs <lang> <file.json>");
  process.exit(64);
}
const dict = JSON.parse(fs.readFileSync(file, "utf8"));
const body = Object.entries(dict).map(([k, v]) => `  ${JSON.stringify(k)}:\n    ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(
  `src/lib/shared/i18n/${lang}.ts`,
  `// ${lang} participant translations. DRAFT until approved by a native speaker and the programme.\n// Generated by scripts/i18n-import.mjs; keys are the exact English text.\nimport type { Dictionary } from ".";\n\nconst d: Dictionary = {\n${body}\n};\nexport default d;\n`,
);
console.log(`${lang}: ${Object.keys(dict).length} entries`);
